export function typeTone(sqlType: string) {
  const t = sqlType.toLowerCase()
  if (['int', 'bigint', 'smallint', 'tinyint', 'decimal', 'numeric', 'money', 'float', 'real'].includes(t)) {
    return 'num'
  }
  if (['date', 'datetime', 'datetime2', 'smalldatetime', 'time'].includes(t)) {
    return 'date'
  }
  if (t === 'bit') {
    return 'bool'
  }
  return 'text'
}
